using System.Globalization;
using System.Text;

namespace OtsLauncher.Core;

public sealed class OtClientConfigWriter
{
    public void Write(ResolvedProfile profile, string clientRoot)
    {
        var layout = new OtClientLayout(clientRoot);
        layout.Ensure();

        // Redemption must keep its own bootstrap. Apply our settings after its
        // defaults, before the logger, settings directory and modules are opened.
        const string hook = "dofile('/config/ots-network.lua') -- OTS launcher bootstrap";
        const string anchor = "-- setup logger";
        if (!File.Exists(layout.InitLua))
            throw new InvalidOperationException("Client init.lua is missing. Repair the client package first.");
        var init = File.ReadAllText(layout.InitLua);
        if (!init.Contains(hook, StringComparison.Ordinal))
        {
            var position = init.IndexOf(anchor, StringComparison.Ordinal);
            if (position < 0)
                throw new InvalidOperationException("Unsupported client init.lua: Redemption bootstrap marker is missing.");
            init = init.Insert(position, hook + "\n\n");
        }

        var host = profile.Server.Host ?? "127.0.0.1";
        var login = profile.Server.LoginPort ?? 7171;
        var game = profile.Server.GamePort ?? login + 1;
        var protocol = int.Parse(profile.Protocol, CultureInfo.InvariantCulture);
        var loginProtocol = protocol >= 1281 ? 1100 : protocol;

        var lua = new StringBuilder();
        lua.AppendLine("-- Generated by Tibernia launcher. Do not edit by hand.");
        lua.AppendLine($"OTS_SERVER_ID = {Q(profile.Id)}");
        lua.AppendLine($"OTS_SERVER_NAME = {Q(profile.Name)}");
        lua.AppendLine($"OTS_SERVER_HOST = {Q(host)}");
        lua.AppendLine($"OTS_SERVER_LOGIN_PORT = {login.ToString(CultureInfo.InvariantCulture)}");
        lua.AppendLine($"OTS_SERVER_GAME_PORT = {game.ToString(CultureInfo.InvariantCulture)}");
        lua.AppendLine($"OTS_PROTOCOL = {Q(profile.Protocol)}");
        lua.AppendLine($"OTS_PROFILE_VERSION = {Q(profile.Package.AssetsVersion)}");
        lua.AppendLine($"OTS_PLATFORM = {Q(profile.Platform.Key)}");
        lua.AppendLine("local version = assert(tonumber(OTS_PROTOCOL), 'Invalid OTS protocol')");
        // Current Canary login servers intentionally expose their legacy TCP
        // account handshake on protocol 11.00. Keep the selected client/game
        // version (and its 15.25 assets/features) unchanged.
        lua.AppendLine($"OTS_LOGIN_PROTOCOL = {loginProtocol.ToString(CultureInfo.InvariantCulture)}");
        lua.AppendLine("OTS_RSA = 'otserv'");
        lua.AppendLine("Servers_init = { [OTS_SERVER_HOST] = { port = OTS_SERVER_LOGIN_PORT, protocol = version, httpLogin = false, useAuthenticator = false } }");
        lua.AppendLine("g_app.setName('Tibernia - ' .. OTS_SERVER_NAME)");
        lua.AppendLine("g_app.setCompactName('ots-' .. OTS_SERVER_ID)");
        lua.AppendLine("if Services and Services.clientAssets then Services.clientAssets.enabled = version >= 1281 end");
        File.WriteAllText(layout.NetworkLua, lua.ToString());
        if (File.ReadAllText(layout.InitLua) != init)
            File.WriteAllText(layout.InitLua, init);
    }

    private static string Q(string value) => "'" + value.Replace("\\", "\\\\").Replace("'", "\\'") + "'";
}
